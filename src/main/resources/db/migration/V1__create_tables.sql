CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    price NUMERIC(12, 2) NOT NULL,
    quantity_in_stock INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    image_path VARCHAR(255),
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_products_owner
        FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT chk_products_price
        CHECK (price >= 0),
    CONSTRAINT chk_products_quantity
        CHECK (quantity_in_stock >= 0),
    CONSTRAINT chk_products_low_stock_threshold
        CHECK (low_stock_threshold >= 0)
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    sale_date DATE NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_sales_owner
        FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT fk_sales_product
        FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT chk_sales_quantity
        CHECK (quantity > 0),
    CONSTRAINT chk_sales_unit_price
        CHECK (unit_price >= 0),
    CONSTRAINT chk_sales_total_amount
        CHECK (total_amount = quantity * unit_price),
    CONSTRAINT chk_sales_status
        CHECK (status IN ('COMPLETED', 'CANCELED')),
    CONSTRAINT chk_sales_canceled_at
        CHECK (
            (status = 'CANCELED' AND canceled_at IS NOT NULL)
            OR
            (status = 'COMPLETED' AND canceled_at IS NULL)
        )
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    sale_id BIGINT,
    type VARCHAR(25) NOT NULL,
    quantity_change INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,
    reason VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_stock_movements_product
        FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_stock_movements_sale
        FOREIGN KEY (sale_id) REFERENCES sales(id),
    CONSTRAINT chk_stock_movements_type
        CHECK (type IN ('INITIAL', 'SALE', 'SALE_CANCELLATION', 'ADJUSTMENT')),
    CONSTRAINT chk_stock_movements_quantity_change
        CHECK (quantity_change <> 0),
    CONSTRAINT chk_stock_movements_quantity_after
        CHECK (quantity_after >= 0),
    CONSTRAINT chk_stock_movements_adjustment_reason
        CHECK (type <> 'ADJUSTMENT' OR reason IS NOT NULL)
);

CREATE INDEX idx_products_owner_archived
    ON products (owner_id, archived_at);

CREATE INDEX idx_sales_owner_sale_date
    ON sales (owner_id, sale_date DESC);

CREATE INDEX idx_sales_product
    ON sales (product_id);

CREATE INDEX idx_stock_movements_product_created
    ON stock_movements (product_id, created_at DESC);
